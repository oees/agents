"""Codex target: a managed block at the bottom of AGENTS.md.

Codex reads AGENTS.md as plain text and resolves no imports, so the block
embeds the project context and the full body of every rule it applies.
"""

from collections.abc import Iterator

from oees_agents.content import Content, Document
from oees_agents.context import context_block
from oees_agents.manifest import Manifest
from oees_agents.output import ManagedBlock, Output

AGENTS_MD = "AGENTS.md"
CODEX_INSTRUCTION_LIMIT = 32 * 1024
"""Codex's default combined instruction size (`project_doc_max_bytes`)."""

HEADER = """\
## Shared engineering rules

Generated by oees-agents from `.oees-agents.toml`. Edit the manifest and run
`oees-agents update`; keep project instructions outside this block. Apply
these rules to every task, including delegated work. Project-specific
instructions specialize the defaults. Report unresolved instruction conflicts."""


def render(manifest: Manifest, content: Content) -> Output:
    context = context_block(manifest, content)
    sections = [] if context is None else [context.strip("\n")]
    sections.append(HEADER)
    sections.extend(_section(document) for document in _rules(manifest, content))
    block = ManagedBlock(
        body="\n\n".join(sections) + "\n",
        placement="bottom",
        max_bytes=CODEX_INSTRUCTION_LIMIT,
    )
    return Output(blocks={AGENTS_MD: block})


def _rules(manifest: Manifest, content: Content) -> Iterator[Document]:
    yield from content.conduct.values()
    for name in manifest.defaults:
        yield content.defaults[name]


def _section(document: Document) -> str:
    body = document.body.strip("\n")
    return f"<!-- Source: {document.source} -->\n{body}"
