"""Codex target: a managed block at the bottom of AGENTS.md, or a session hook.

Codex reads AGENTS.md as plain text and resolves no imports, so the block
embeds the project context and the full body of every rule it applies.

A machine install does not write ~/.codex/AGENTS.md: Codex loads that file in
every project and has no setting to skip it. The rules go to their own file,
and a SessionStart hook prints them only where no AGENTS.md that Codex loads
holds them already. So a project's own rules apply, not both.
"""

import json
import shlex
from pathlib import Path

from oees_agents.blocks import BEGIN
from oees_agents.content import Content, Document
from oees_agents.context import context_block
from oees_agents.manifest import Manifest
from oees_agents.output import ManagedBlock, Output
from oees_agents.scope import Layout

CODEX_INSTRUCTION_LIMIT = 32 * 1024
"""Codex's default combined instruction size (`project_doc_max_bytes`)."""

HEADER = """\
## Shared engineering rules

Generated by oees-agents from `.oees-agents.toml`. Edit the manifest and run
`{update}`{own}. Apply
these rules to every task, including delegated work. Project-specific
instructions specialize the defaults. Report unresolved instruction conflicts."""
OWN_INSTRUCTIONS = "; keep your own instructions outside this block"

MACHINE_DIR = "oees-agents"
# New sessions, /clear and compaction start a new context. A resumed or forked
# session already holds the rules in its history.
NEW_CONTEXT = "^(startup|clear|compact)$"

# Runs in the session's working directory. Codex loads, in each directory from
# the Git root down, AGENTS.override.md or else AGENTS.md. If one of them already
# holds the shared rules (a project install), the machine rules stay out.
SESSION_START = f"""\
#!/bin/sh
# Generated by oees-agents. Codex runs this at session start (see hooks.json).
# It prints the OEES shared rules, unless an AGENTS.md that Codex loads here
# already holds them.
dir=$PWD
while :; do
  loaded="$dir/AGENTS.override.md"
  [ -f "$loaded" ] || loaded="$dir/AGENTS.md"
  if grep -qsF '{BEGIN}' "$loaded"; then
    exit 0
  fi
  if [ -e "$dir/.git" ] || [ "$dir" = / ]; then
    break
  fi
  dir=$(dirname "$dir")
done
cat "$(dirname "$0")/rules.md"
"""


def render(manifest: Manifest, content: Content, layout: Layout) -> Output:
    if layout.scope == "machine":
        return _machine(manifest, content, layout)
    block = ManagedBlock(
        body=_body(manifest, content, layout, own=OWN_INSTRUCTIONS),
        placement="bottom",
        max_bytes=CODEX_INSTRUCTION_LIMIT,
    )
    return Output(blocks={"AGENTS.md": block})


def _machine(manifest: Manifest, content: Content, layout: Layout) -> Output:
    script = f"{layout.codex}/{MACHINE_DIR}/session-start.sh"
    hooks = f"{layout.codex}/hooks.json"
    hooks_json = _hooks(layout.root / script)
    files = {
        f"{layout.codex}/{MACHINE_DIR}/rules.md": _body(manifest, content, layout, own="").encode(),
        script: SESSION_START.encode(),
        hooks: hooks_json,
    }
    return Output(
        files=files,
        optional={
            hooks: "Codex reads the machine rules through a session hook. Add it to yours:\n"
            + hooks_json.decode()
        },
        notes={hooks: "Codex runs the hook only after you approve it: start Codex and run /hooks."},
    )


def _hooks(script: Path) -> bytes:
    handler = {
        "type": "command",
        "command": f"sh {shlex.quote(str(script))}",
        "statusMessage": "Loading the OEES shared rules",
        # Codex moves larger hook output to a file and shows a preview; 0 keeps it all.
        "additionalContextLimit": 0,
    }
    data = {
        "description": "Generated by oees-agents: the machine install's shared rules.",
        "hooks": {"SessionStart": [{"matcher": NEW_CONTEXT, "hooks": [handler]}]},
    }
    return (json.dumps(data, indent=2) + "\n").encode()


def _body(manifest: Manifest, content: Content, layout: Layout, own: str) -> str:
    sections = []
    if manifest.project is not None:
        context = context_block(manifest.project, manifest.kits, content.context_template)
        sections.append(context.strip("\n"))
    sections.append(HEADER.format(update=layout.update_command, own=own))
    sections.extend(_section(document) for document in content.rules(manifest.defaults))
    return "\n\n".join(sections) + "\n"


def _section(document: Document) -> str:
    body = document.body.strip("\n")
    return f"<!-- Source: {document.source} -->\n{body}"
