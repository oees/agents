def test_install_into_a_spaced_directory_embeds_every_body_once_and_is_idempotent(
    tmp_path: Path, content_root: Path
) -> None:
    root = tmp_path / "repo with spaces"
    root.mkdir()
    content = load_content(content_root)

    sync(root, content_root, manifest())

    installed = (root / "AGENTS.md").read_bytes()
    text = installed.decode()
    assert marker_count(installed, BEGIN) == 1
    assert marker_count(installed, END) == 1
    for document in (*content.conduct.values(), *content.defaults.values()):
        assert document.body.strip("\n") in text, document.source
    assert not re.search(r"^(description:|@rules/)", text, re.MULTILINE)
    sync(root, content_root, manifest())
    assert (root / "AGENTS.md").read_bytes() == installed


def test_update_replaces_outdated_rules_and_keeps_local_lines_first_and_last(
    tmp_path: Path, content_root: Path
) -> None:
    path = tmp_path / "AGENTS.md"
    path.write_text(
        f"Local instructions before the block.\n{BEGIN}\nOutdated shared instructions.\n"
        f"{END}\nLocal instructions after the block.\n"
    )
    write(
        content_root / "content/defaults/tdd.md",
        "---\ndescription: Fixture rule\n---\n# Test policy\nUse the original test policy.\n",
    )

    sync(tmp_path, content_root, manifest())

    lines = path.read_text().splitlines()
    assert lines[0] == "Local instructions before the block."
    assert lines[-1] == "Local instructions after the block."
    assert "Use the original test policy." in lines
    assert "Outdated shared instructions." not in path.read_text()
    first = path.read_bytes()
    sync(tmp_path, content_root, manifest())
    assert path.read_bytes() == first

    write(
        content_root / "content/defaults/tdd.md",
        "---\ndescription: Fixture rule\n---\n# Test policy\nUse the updated test policy.\n",
    )
    sync(tmp_path, content_root, manifest())

    lines = path.read_text().splitlines()
    assert "Use the updated test policy." in lines
    assert "Use the original test policy." not in path.read_text()
    assert lines[0] == "Local instructions before the block."
    assert lines[-1] == "Local instructions after the block."


@pytest.mark.parametrize(
    "existing",
    [
        f"Local policy.\n{BEGIN}\nStale policy.\n",
        f"Local policy.\n{END}\n",
        f"{BEGIN}\n{END}\n{BEGIN}\n{END}\n",
        f"{END}\nLocal policy.\n{BEGIN}\n",
    ],
    ids=["unclosed", "orphan", "duplicate", "reversed"],
)
def test_malformed_or_multiple_markers_are_refused_without_changing_the_file(
    tmp_path: Path, content_root: Path, existing: str
) -> None:
    path = write(tmp_path / "AGENTS.md", existing)
    before = path.read_bytes()

    with pytest.raises(BlockError, match="markers"):
        sync(tmp_path, content_root, manifest())

    assert path.read_bytes() == before


def test_a_symlinked_agents_md_is_refused_and_the_link_and_target_are_untouched(
    tmp_path: Path, content_root: Path
) -> None:
    root = tmp_path / "symlink target"
    root.mkdir()
    original = write(tmp_path / "linked instructions.md", "Do not modify these instructions.\n")
    before = original.read_bytes()
    (root / "AGENTS.md").symlink_to(original)

    with pytest.raises(BlockError, match="symlink"):
        sync(root, content_root, manifest())

    assert (root / "AGENTS.md").is_symlink()
    assert os.readlink(root / "AGENTS.md") == str(original)
    assert original.read_bytes() == before


def test_a_crlf_agents_md_keeps_local_bytes_and_gets_one_current_block(
    tmp_path: Path, content_root: Path
) -> None:
    (content_root / "content/defaults/crlf.md").write_bytes(
        b"---\r\ndescription: CRLF fixture rule\r\n---\r\n"
        b"# CRLF policy\r\nUse the current CRLF policy.\r\n"
    )
    prefix = b"Local instructions before the block.\r\n\r\n"
    suffix = b"\r\nLocal instructions after the block.\r\n"
    path = tmp_path / "AGENTS.md"
    path.write_bytes(prefix + f"{BEGIN}\r\nOutdated CRLF policy.\r\n{END}\r\n".encode() + suffix)

    sync(tmp_path, content_root, manifest(defaults=("crlf",)))

    result = path.read_bytes()
    normalized = result.replace(b"\r\n", b"\n").decode()
    assert result.startswith(prefix)
    assert result.endswith(suffix)
    assert b"\n" not in result.replace(b"\r\n", b"")
    assert marker_count(result, BEGIN) == 1
    assert marker_count(result, END) == 1
    assert b"Outdated CRLF policy." not in result
    assert not re.search(r"^(description:|---$)", normalized, re.MULTILINE)
    assert "Use the current CRLF policy." in normalized.split("\n")
    sync(tmp_path, content_root, manifest(defaults=("crlf",)))
    assert path.read_bytes() == result


def test_an_agents_md_over_32_kib_is_still_produced_with_a_warning(
    tmp_path: Path, content_root: Path
) -> None:
    local = "Local instructions that are long.\n" * 1_000
    write(tmp_path / "AGENTS.md", local)

    warnings = sync(tmp_path, content_root, manifest())

    assert len(warnings) == 1
    assert str(CODEX_INSTRUCTION_LIMIT) in warnings[0]
    installed = (tmp_path / "AGENTS.md").read_text()
    assert installed.startswith(local)
    assert marker_count(installed.encode(), BEGIN) == 1


def test_a_small_agents_md_produces_no_warning(tmp_path: Path, content_root: Path) -> None:
    assert sync(tmp_path, content_root, manifest()) == []


def test_the_context_block_appears_once_inside_the_block_before_the_rules(
    tmp_path: Path, content_root: Path
) -> None:
    sync(tmp_path, content_root, manifest())
    sync(tmp_path, content_root, manifest())

    text = (tmp_path / "AGENTS.md").read_text()
    assert text.count(CONTEXT_BEGIN) == 1
    assert text.index(BEGIN) < text.index(CONTEXT_BEGIN) < text.index(HEADING)
    assert "**octohub**: B2B multi-tenant platform" in text


def test_there_is_no_context_block_without_a_project(content_root: Path) -> None:
    body = render(manifest(project=None), load_content(content_root)).blocks["AGENTS.md"].body

    assert CONTEXT_BEGIN not in body
    assert body.startswith(HEADING)


def test_an_opted_out_default_is_absent_from_the_block(content_root: Path) -> None:
    content = load_content(content_root)
    opted_in = tuple(name for name in DEFAULTS if name != "migrations")

    body = render(manifest(defaults=opted_in), content).blocks["AGENTS.md"].body

    assert "content/defaults/migrations.md" not in body
    assert "# Migrations" not in body
    for name in (*CONDUCT, *opted_in):
        assert f"# {name.title()}\n" in body
