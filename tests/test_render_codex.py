import os
import re
from pathlib import Path

import pytest

from oees_agents.blocks import BEGIN, END, BlockError, merge
from oees_agents.content import load_content
from oees_agents.manifest import Manifest, Project
from oees_agents.targets.codex import CODEX_INSTRUCTION_LIMIT, render

from conftest import CONDUCT, DEFAULTS, write

PROJECT = Project(
    name="octohub",
    description="B2B multi-tenant platform where partners and vendors sell energy products.",
    users="external partners, vendors, OEES operations",
    blast_radius="customer-facing",
    default_branch="main",
    check="make check",
    check_fast="make check-fast",
)
CONTEXT_BEGIN = "<!-- BEGIN OEES PROJECT CONTEXT -->"
HEADING = "## Shared engineering rules"


def manifest(defaults: tuple[str, ...] = DEFAULTS, project: Project | None = PROJECT) -> Manifest:
    return Manifest(source="v1.0.0", targets=("codex",), project=project, defaults=defaults)


def sync(root: Path, content_root: Path, project_manifest: Manifest) -> list[str]:
    """Render and write AGENTS.md the way the writer will, returning merge warnings."""
    output = render(project_manifest, load_content(content_root))
    path = root / "AGENTS.md"
    data, warnings = merge(path, output.blocks["AGENTS.md"])
    path.write_bytes(data)
    return warnings


def marker_count(data: bytes, marker: str) -> int:
    return data.replace(b"\r\n", b"\n").split(b"\n").count(marker.encode())


def test_codex_renders_one_bottom_block_in_agents_md_and_no_files(content_root: Path) -> None:
    output = render(manifest(), load_content(content_root))

    assert output.files == {}
    assert set(output.blocks) == {"AGENTS.md"}
    block = output.blocks["AGENTS.md"]
    assert block.placement == "bottom"
    assert block.max_bytes == CODEX_INSTRUCTION_LIMIT == 32_768


